#!/usr/bin/env node
'use strict';
// Generates ported-server.js by stripping the `require(...)` and
// `module.exports = {...}` lines from the original server-side modules in
// webapp/server/, in dependency order, and concatenating them into one plain
// (non-module) script that can run directly in a browser. This is a
// mechanical transformation, not a rewrite: the ported functions are
// byte-for-byte identical to the server logic (constants, normalization,
// filtering, stats, search) other than the CommonJS boilerplate removed.
// Re-run this after editing anything under webapp/server/{ingest/,
// analysis.js,stats.js,search.js} to keep this build in sync.

const fs = require('fs');
const path = require('path');

const files = [
  '../webapp/server/ingest/constants.js',
  '../webapp/server/ingest/normalize.js',
  '../webapp/server/ingest/validate.js',
  '../webapp/server/stats.js',
  '../webapp/server/analysis.js',
  '../webapp/server/search.js',
];

let out = "'use strict';\n" +
  "// Auto-generated by port-server-modules.js -- DO NOT EDIT DIRECTLY.\n" +
  "// Source of truth is webapp/server/{ingest/constants,ingest/normalize,ingest/validate,stats,analysis,search}.js\n" +
  "// Re-run `node port-server-modules.js` after editing any of those.\n";

for (const relPath of files) {
  let content = fs.readFileSync(path.join(__dirname, relPath), 'utf8');
  content = content.replace(/^'use strict';\s*\n/, '');
  content = content.replace(/^const\s*\{[^}]*\}\s*=\s*require\([^)]*\);\s*$/gm, '');
  content = content.replace(/^module\.exports\s*=\s*\{[\s\S]*?\};\s*$/m, '');
  out += `\n/* ============ ported from ${relPath} ============ */\n` + content.trim() + '\n';
}

const outPath = path.join(__dirname, 'ported-server.js');
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${out.length} bytes) from ${files.length} source files.`);
